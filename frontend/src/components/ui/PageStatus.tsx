/**
 * Строка статуса страницы: итог действия — «Запись отменена», «Данные сохранены».
 * Регион должен быть смонтирован в любом состоянии страницы и стоять на одном месте среди соседей:
 * сообщение, появившееся в уже существующем регионе, скринридер озвучит, а в только что появившемся — нет.
 */
export function PageStatus({ message }: { message: string }) {
  return (
    <p role="status" className="mb-4 text-sm font-semibold text-primary empty:mb-0">
      {message}
    </p>
  )
}
